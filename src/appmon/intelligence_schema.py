"""Additive tables for the observation console. No estimated metrics."""
from .db import APP_KEY, REGION

TABLES = {
    'watchlist': f'''id BIGINT AUTO_INCREMENT PRIMARY KEY, {APP_KEY}, {REGION},
        group_name VARCHAR(120) NOT NULL, refresh_hours DOUBLE NOT NULL DEFAULT 24,
        enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at DOUBLE NOT NULL,
        UNIQUE KEY watch_identity(store,app_id,country,language), INDEX watch_group(group_name)''',
    'observation_targets': f'''id BIGINT AUTO_INCREMENT PRIMARY KEY,
        kind VARCHAR(20) NOT NULL, {APP_KEY}, {REGION}, collection VARCHAR(64) NOT NULL DEFAULT '',
        category VARCHAR(64) NOT NULL DEFAULT '', depth INT NOT NULL DEFAULT 100,
        refresh_hours DOUBLE NOT NULL DEFAULT 24, enabled BOOLEAN NOT NULL DEFAULT TRUE,
        due DOUBLE NOT NULL DEFAULT 0, lease_until DOUBLE NOT NULL DEFAULT 0, token CHAR(32),
        failures INT NOT NULL DEFAULT 0, last_error TEXT, latest_attempt_id BIGINT,
        latest_success_id BIGINT, previous_success_id BIGINT,
        UNIQUE KEY observation_identity(kind,store,app_id,country,language,collection,category),
        INDEX observation_due(enabled,due,lease_until)''',
    'observation_runs': '''id BIGINT AUTO_INCREMENT PRIMARY KEY, target_id BIGINT NOT NULL,
        observed_at DOUBLE NOT NULL, outcome VARCHAR(16) NOT NULL, source VARCHAR(128) NOT NULL,
        parser_version VARCHAR(32) NOT NULL, coverage VARCHAR(64) NOT NULL,
        returned_count INT, raw_path TEXT, error TEXT, INDEX observation_history(target_id,id)''',
    'observation_items': '''run_id BIGINT NOT NULL, item_id VARCHAR(512) CHARACTER SET ascii NOT NULL,
        position INT NOT NULL, payload LONGTEXT NOT NULL, PRIMARY KEY(run_id,item_id),
        INDEX observation_item(item_id,run_id)''',
    'reviews': f'''{APP_KEY}, {REGION}, review_id VARCHAR(255) CHARACTER SET ascii NOT NULL,
        rating INT NOT NULL, content TEXT NOT NULL, title TEXT, version VARCHAR(120),
        published_at VARCHAR(64), first_seen DOUBLE NOT NULL, last_seen DOUBLE NOT NULL,
        payload LONGTEXT NOT NULL, PRIMARY KEY(store,app_id,country,language,review_id),
        INDEX review_time(last_seen), INDEX review_rating(rating)''',
    'alert_rules': '''id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
        kind VARCHAR(32) NOT NULL, threshold DOUBLE NOT NULL DEFAULT 5,
        group_name VARCHAR(120) NOT NULL DEFAULT '', enabled BOOLEAN NOT NULL DEFAULT TRUE,
        created_at DOUBLE NOT NULL''',
    'alerts': '''id BIGINT AUTO_INCREMENT PRIMARY KEY, rule_id BIGINT NOT NULL,
        fingerprint CHAR(64) NOT NULL UNIQUE, observed_at DOUBLE NOT NULL,
        kind VARCHAR(32) NOT NULL, title TEXT NOT NULL, payload LONGTEXT NOT NULL,
        acknowledged BOOLEAN NOT NULL DEFAULT FALSE, INDEX alert_time(observed_at,id)''',
    'alert_cursors': '''source VARCHAR(32) PRIMARY KEY, last_id BIGINT NOT NULL DEFAULT 0''',
    'exports': '''id CHAR(32) PRIMARY KEY, kind VARCHAR(32) NOT NULL, filters LONGTEXT NOT NULL,
        status VARCHAR(16) NOT NULL DEFAULT 'queued', created_at DOUBLE NOT NULL,
        finished_at DOUBLE, rows_written BIGINT NOT NULL DEFAULT 0, error TEXT,
        lease_until DOUBLE NOT NULL DEFAULT 0, token CHAR(32)''',
    'ad_observations': '''id BIGINT AUTO_INCREMENT PRIMARY KEY, fingerprint CHAR(64) NOT NULL UNIQUE,
        store VARCHAR(16) NOT NULL, app_id VARCHAR(512) CHARACTER SET ascii NOT NULL,
        country CHAR(2) NOT NULL, keyword VARCHAR(255) NOT NULL, observed_at DOUBLE NOT NULL,
        source VARCHAR(255) NOT NULL, evidence_url TEXT NOT NULL, placement VARCHAR(120) NOT NULL,
        payload LONGTEXT NOT NULL, INDEX ad_app(store,app_id,country), INDEX ad_time(observed_at)''',
    'ad_reports': '''id BIGINT AUTO_INCREMENT PRIMARY KEY, fingerprint CHAR(64) NOT NULL UNIQUE,
        report_date CHAR(10) NOT NULL, app_id VARCHAR(512) CHARACTER SET ascii NOT NULL,
        country CHAR(2) NOT NULL, campaign VARCHAR(255) NOT NULL, keyword VARCHAR(255) NOT NULL,
        impressions BIGINT NOT NULL, taps BIGINT NOT NULL, installs BIGINT NOT NULL,
        spend DECIMAL(18,6) NOT NULL, currency CHAR(3) NOT NULL, source VARCHAR(255) NOT NULL,
        imported_at DOUBLE NOT NULL, INDEX report_app(app_id,country,report_date)''',
}
