"""Additive discovery storage; public metrics are never private sales estimates."""
def tables(app_key, region):
    return {
        'app_metrics_daily': f'''{app_key}, {region}, day BIGINT NOT NULL,
            observed_at DOUBLE NOT NULL, source VARCHAR(64) NOT NULL, parser_version VARCHAR(32) NOT NULL,
            name TEXT, category VARCHAR(128), released_at DOUBLE, installs_min BIGINT,
            installs_reported BIGINT, ratings BIGINT, rating DOUBLE, price DOUBLE,
            currency VARCHAR(16), has_ads BOOLEAN, has_iap BOOLEAN, raw_path TEXT,
            PRIMARY KEY(store,app_id,country,language,day),
            INDEX metric_market(store,country,language,day)''',
        'keyword_candidates': '''id BIGINT AUTO_INCREMENT PRIMARY KEY,
            store VARCHAR(16) CHARACTER SET ascii NOT NULL, country CHAR(2) CHARACTER SET ascii NOT NULL,
            language VARCHAR(16) CHARACTER SET ascii NOT NULL, keyword VARCHAR(255) NOT NULL,
            source_key CHAR(64) CHARACTER SET ascii NOT NULL, source VARCHAR(255) NOT NULL,
            source_url TEXT NOT NULL, license_name VARCHAR(128) NOT NULL, attribution TEXT NOT NULL,
            corpus_frequency BIGINT, source_period VARCHAR(64) NOT NULL, imported_at DOUBLE NOT NULL,
            UNIQUE KEY candidate_identity(store,country,language,keyword,source_key),
            INDEX candidate_market(store,country,language,id)''',
        'keyword_reports': f'''id BIGINT AUTO_INCREMENT PRIMARY KEY, {app_key}, {region},
            digest CHAR(64) CHARACTER SET ascii NOT NULL, filename TEXT NOT NULL, source VARCHAR(128) NOT NULL,
            observed_at DOUBLE NOT NULL, imported_at DOUBLE NOT NULL, raw_path TEXT NOT NULL, summary LONGTEXT NOT NULL,
            UNIQUE KEY report_identity(store,app_id,country,language,digest)''',
        'keyword_report_rows': '''report_id BIGINT NOT NULL, sheet VARCHAR(64) NOT NULL, source_row INT NOT NULL,
            keyword VARCHAR(255) NOT NULL, position INT, popularity DOUBLE, search_index DOUBLE, payload LONGTEXT NOT NULL,
            PRIMARY KEY(report_id,sheet,source_row), INDEX report_keyword(keyword,report_id)''',
        'keyword_signal_runs': '''id BIGINT AUTO_INCREMENT PRIMARY KEY,
            store VARCHAR(16) CHARACTER SET ascii NOT NULL, country CHAR(2) CHARACTER SET ascii NOT NULL,
            language VARCHAR(16) CHARACTER SET ascii NOT NULL, source VARCHAR(255) NOT NULL,
            source_url TEXT NOT NULL, kind VARCHAR(32) NOT NULL, observed_at DOUBLE NOT NULL,
            score_unit VARCHAR(128) NOT NULL, fingerprint CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
            imported_at DOUBLE NOT NULL, INDEX signal_market(store,country,language,observed_at)''',
        'keyword_signals': '''run_id BIGINT NOT NULL, keyword VARCHAR(255) NOT NULL,
            position INT NOT NULL, score DOUBLE, PRIMARY KEY(run_id,keyword),
            UNIQUE KEY signal_position(run_id,position)''',
    }
